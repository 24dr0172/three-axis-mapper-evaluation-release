#!/usr/bin/env python3
"""Generate Phase 2 derived tables from frozen M6-A2 and R10 authorities."""

from __future__ import annotations

import csv
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
TEX_M6 = ROOT / "manuscript" / "tables" / "m6a2_stability.tex"
TEX_R10 = ROOT / "manuscript" / "tables" / "r10_accounting.tex"
TEX_ENV = ROOT / "manuscript" / "tables" / "environment_provenance.tex"


def f6(x) -> str:
    return f"{float(x):.6f}"


def write_m6a2() -> None:
    rows = list(csv.DictReader((ROOT / "evidence/baseline/m6a2/per_run_metrics.csv").open()))
    sigmas = ["0.01", "0.03", "0.05", "0.08", "0.1"]
    rng = np.random.default_rng(20260830)
    lines = [
        "% Auto-generated by revision_v4_1/generate_phase2_tables.py. Do not hand-edit.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{M6-A2 Swiss extended-persistence bottleneck displacement relative to the clean baseline. Each row uses matched replication IDs and perturbation seeds. Percentile-bootstrap 95\% intervals ($B=5000$, seed 20260830) resample replicate-level Conventional-minus-F-Mapper differences. Negative values favor Conventional Mapper.}",
        r"\label{tab:m6a2}",
        r"\small",
        r"\begin{tabular}{@{}cccccc@{}}",
        r"\toprule",
        r"$\sigma$ & $n$ pairs & Mean Conv. & Mean F-Mapper & Mean paired difference & 95\% paired-bootstrap interval \\",
        r"\midrule",
    ]
    for sigma in sigmas:
        by_rep = {}
        for row in rows:
            if row["noise_sigma"] != sigma or row["status"] != "success" or not row["bottleneck_distance"]:
                continue
            by_rep.setdefault(int(row["replication_id"]), {})[row["method_id"]] = (
                float(row["bottleneck_distance"]), row["perturbation_seed"]
            )
        pairs = [values for _, values in sorted(by_rep.items()) if {"conventional", "f_mapper"}.issubset(values)]
        if any(values["conventional"][1] != values["f_mapper"][1] for values in pairs):
            raise SystemExit("M6-A2 perturbation-seed pairing drifted")
        conventional = np.asarray([values["conventional"][0] for values in pairs])
        fmapper = np.asarray([values["f_mapper"][0] for values in pairs])
        differences = conventional - fmapper
        boot = differences[rng.integers(0, len(differences), size=(5000, len(differences)))].mean(axis=1)
        lo, hi = np.quantile(boot, [0.025, 0.975])
        display_sigma = "0.10" if sigma == "0.1" else sigma
        note = r"$^{\dagger}$" if sigma == "0.1" else ""
        lines.append(
            f"${display_sigma}$ & {len(pairs)}{note} & ${f6(conventional.mean())}$ & "
            f"${f6(fmapper.mean())}$ & ${f6(differences.mean())}$ & "
            f"$[{f6(lo)},{f6(hi)}]$ \\\\"
        )
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            r"\par\vspace{0.4em}{\scriptsize $^{\dagger}$ One F-Mapper construction at $\sigma=0.10$ was non-convergent under the frozen solver criterion; its matched Conventional run is omitted, leaving 29 pairs.}",
            r"\end{table}",
            "",
        ]
    )
    TEX_M6.parent.mkdir(parents=True, exist_ok=True)
    TEX_M6.write_text("\n".join(lines))


def write_r10() -> None:
    acc = json.loads((ROOT / "evidence/baseline/r10/R10_V4_RUN_ACCOUNTING.json").read_text())
    lines = [
        "% Auto-generated by revision_v4_1/generate_phase2_tables.py. Do not hand-edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{R10 structural-robustness accounting for Conventional and Ball Mapper. Degenerate and successful-ineligible rows remain in the attempt-level denominator; they are not converted into distances.}",
        r"\label{tab:r10account}",
        r"\small",
        r"\begin{tabular}{@{}lcccc@{}}",
        r"\toprule",
        r"Arm & Attempted & Eligible & Successful-ineligible & Typed degenerate \\",
        r"\midrule",
        f"Clean & {acc['clean']['attempted']} & {acc['clean']['eligible']} & {acc['clean']['ineligible']} & {acc['clean']['failed']} \\\\",
        f"Noisy & {acc['noisy']['attempted']} & {acc['noisy']['eligible']} & {acc['noisy']['ineligible']} & {acc['noisy']['failed']} \\\\",
        f"Total & {acc['attempted']} & {acc['eligible']} & {acc['success_ineligible_retained']} & {acc['execution_failed']} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    TEX_R10.write_text("\n".join(lines))
    if acc["attempted"] != 282 or acc["eligible"] != 205:
        raise SystemExit("R10 accounting drifted from the frozen 282/205 charter")


def write_env() -> None:
    lines = [
        "% Auto-generated by revision_v4_1/generate_phase2_tables.py. Do not hand-edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Recorded execution environments. The portable release verifier is the CPython~3.12 family. Conventional III-1 and III-2 evidence was produced under the separately recorded CPython~3.13.5 family.}",
        r"\label{tab:envprov}",
        r"\small",
        r"\begin{tabularx}{\textwidth}{@{}lX@{}}",
        r"\toprule",
        r"Family & Role \\",
        r"\midrule",
        r"CPython 3.12.x + \texttt{environment/requirements.txt} & Portable verification and representative replay; GUDHI 3.13.0; fail-closed interpreter check \\",
        r"CPython 3.12.3 lock \texttt{ENVIRONMENT\_LOCK\_MANIFEST.json} & Production lock bound by later campaign ledgers \\",
        r"CPython 3.13.5 + \texttt{environment/requirements\_axis3\_legacy.txt} & Conventional III-1 and III-2 evidence provenance; not the portable verifier \\",
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{table}",
        "",
    ]
    TEX_ENV.write_text("\n".join(lines))


def main() -> None:
    write_m6a2()
    write_r10()
    write_env()
    print(f"wrote {TEX_M6}")
    print(f"wrote {TEX_R10}")
    print(f"wrote {TEX_ENV}")


if __name__ == "__main__":
    main()
